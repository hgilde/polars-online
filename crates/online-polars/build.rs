//! The index of the frozen state fixtures, discovered from the directory.
//!
//! `tests/state_fixtures.rs` includes `$OUT_DIR/state_fixtures_index.rs`,
//! which this writes from what `tests/state_fixtures/` holds: every
//! `<case>.rs` there is the current schema's set, and every `<case>.rs`
//! under a `v<N>/` beside them is the set kept for schema `N`. Nothing is
//! listed by hand, so two branches that each add a fixture add two files
//! and touch no shared list (docs/PLAN.md task 281 (4)). The library
//! itself reads nothing of it.
//!
//! The same file is `online-polars`' `build.rs`, byte for byte; that
//! crate's `state_fixtures.rs` test holds the two equal.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The `.rs` files directly in `dir`, by name, sorted.
fn fixtures_in(dir: &Path) -> Vec<(String, PathBuf)> {
    let mut found: Vec<(String, PathBuf)> = std::fs::read_dir(dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.is_file() && p.extension().is_some_and(|x| x == "rs"))
                .filter_map(|p| Some((p.file_stem()?.to_str()?.to_owned(), p)))
                // A set written by hand before discovery listed itself in an
                // `index.rs`; it is no fixture.
                .filter(|(name, _)| name != "index")
                .collect()
        })
        .unwrap_or_default();
    found.sort();
    found
}

/// One set as a module: a module a fixture, each including its file by
/// its absolute path, and `ALL`, every fixture of the set by name.
fn set(out: &mut String, module: &str, files: &[(String, PathBuf)]) {
    writeln!(out, "pub mod {module} {{").unwrap();
    writeln!(out, "    #[allow(unused_imports)]\n    use super::Fixture;").unwrap();
    for (name, path) in files {
        // `{:?}` escapes the path as a string literal, a Windows one's
        // backslashes included.
        let path = path.to_str().expect("a fixture's path is UTF-8");
        writeln!(
            out,
            "    pub mod {name} {{\n        include!({path:?});\n    }}"
        )
        .unwrap();
    }
    writeln!(out, "    /// Every fixture of the set, by name.").unwrap();
    writeln!(out, "    pub const ALL: &[&Fixture] = &[").unwrap();
    for (name, _) in files {
        writeln!(out, "        &{name}::FIXTURE,").unwrap();
    }
    writeln!(out, "    ];\n}}").unwrap();
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dir = root.join("tests").join("state_fixtures");
    // A directory is scanned whole, so a fixture added, removed or
    // rewritten, in the current set or a kept one, writes the index again.
    // A package without its tests (an sdist may leave them out) has no
    // fixtures and an empty index, which only the tests read.
    if dir.is_dir() {
        println!("cargo:rerun-if-changed={}", dir.display());
    }
    println!("cargo:rerun-if-changed=build.rs");

    let mut kept: Vec<(u32, PathBuf)> = std::fs::read_dir(&dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.is_dir())
                .filter_map(|p| {
                    let schema = p.file_name()?.to_str()?.strip_prefix('v')?.parse().ok()?;
                    Some((schema, p))
                })
                .collect()
        })
        .unwrap_or_default();
    kept.sort();

    let mut out = String::from(
        "// @generated by build.rs from tests/state_fixtures/: do not edit.\n\
         // The current set, `ALL`, and each set kept for a schema before it.\n\n",
    );
    set(&mut out, "current", &fixtures_in(&dir));
    out.push_str("pub use current::ALL;\n\n");
    for (schema, path) in &kept {
        set(&mut out, &format!("v{schema}"), &fixtures_in(path));
    }
    out.push_str(
        "\n/// Each kept schema and its set, the oldest first: every `v<N>/` \
         directory found.\npub const PREVIOUS_SETS: &[(u32, &[&Fixture])] = &[\n",
    );
    for (schema, _) in &kept {
        writeln!(out, "    ({schema}, v{schema}::ALL),").unwrap();
    }
    out.push_str("];\n");

    let target = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("state_fixtures_index.rs");
    // Written only when it changed, so an unchanged index rebuilds nothing.
    if std::fs::read_to_string(&target).ok().as_deref() != Some(out.as_str()) {
        std::fs::write(&target, out).unwrap();
    }
}
