/// The stream the fixture was built from: every row a function of its index
/// alone (integer arithmetic into an exactly representable `f64`, no `sin`),
/// so any window is reproducible on any platform. The group key is
/// **monotone**, which is what `group_close = "monotone"` needs -- `g0` for
/// the first 25 rows, `g1` for the next 25, `g2` for the rest -- so by row
/// 60 two groups have closed and the third holds ten rows, which is fewer
/// than the `lags` ring wants and so freezes a partly filled one. `y` is
/// null every 13th row, `w` is zero every 10th (the clock advances, nothing
/// is learned), and the session turns over once, at row 30.
fn frame(start: usize, n: usize) -> DataFrame {
    fn lcg(state: &mut u64) -> f64 {
        *state = state
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        (*state >> 11) as f64 / (1u64 << 53) as f64
    }
    let mut t = Vec::with_capacity(n);
    let mut sess = Vec::with_capacity(n);
    let mut g = Vec::with_capacity(n);
    let mut x0 = Vec::with_capacity(n);
    let mut x1 = Vec::with_capacity(n);
    let mut x2 = Vec::with_capacity(n);
    let mut y = Vec::with_capacity(n);
    let mut w = Vec::with_capacity(n);
    for i in start..start + n {
        let mut s = (i as u64) ^ 0x9E37_79B9_7F4A_7C15;
        let a = lcg(&mut s) - 0.5;
        let b = 0.5 * a + 0.3 * (lcg(&mut s) - 0.5);
        let c = 0.25 * (lcg(&mut s) - 0.5);
        t.push(i as f64);
        sess.push(if i < 30 { "s0" } else { "s1" }.to_string());
        g.push(
            match i {
                0..=24 => "g0",
                25..=49 => "g1",
                _ => "g2",
            }
            .to_string(),
        );
        x0.push(a);
        x1.push(b);
        x2.push(c);
        y.push((i % 13 != 5).then_some(2.0 * a - 0.5 * b + 0.25 + c));
        w.push(if i % 10 == 7 { 0.0 } else { 1.0 });
    }
    df!(
        "t" => t, "sess" => sess, "g" => g,
        "x0" => x0, "x1" => x1, "x2" => x2, "y" => y, "w" => w
    )
    .unwrap()
}

fn bytes() -> Vec<u8> {
    (0..SCHEMA5_STATE_HEX.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&SCHEMA5_STATE_HEX[i..i + 2], 16).unwrap())
        .collect()
}

/// The specs are recovered *from* the fixture: a file carries its own, and
/// restating them here would only test that two copies agree.
fn specs_from_fixture() -> Vec<Spec> {
    Bank::load_bytes(&bytes(), None)
        .expect("schema-5 fixture should load without spec expectations")
        .specs()
        .to_vec()
}

fn header(bytes: &[u8]) -> serde_json::Value {
    rmp_serde::from_slice(bytes).expect("a bank file is a msgpack map")
}

/// The bank the fixture is a snapshot of, built afresh in this build.
fn fresh() -> Bank {
    let mut bank = Bank::new(specs_from_fixture()).unwrap();
    for start in (0..60).step_by(20) {
        bank.fit_predict(&frame(start, 20)).unwrap();
    }
    bank
}

const NAMES: [&str; 6] = ["cov", "rc", "eq", "hm", "cc", "bo"];

/// One frame per spec, unnested, so the comparison sees every field.
fn unnested(n: usize, cols: Vec<Column>) -> Vec<DataFrame> {
    let df = DataFrame::new(n, cols).unwrap();
    NAMES
        .iter()
        .map(|name| df.select([*name]).unwrap().unnest([*name], None).unwrap())
        .collect()
}

fn assert_same(want: &[DataFrame], got: &[DataFrame], what: &str) {
    for (w, g) in want.iter().zip(got) {
        assert!(w.equals_missing(g), "{what}:\n{w}\n{g}");
    }
}

/// Everything a bank reports about its state besides predictions: the
/// coefficients, the last learned rows, the data summary, the column
/// statistics and -- new in schema 5 -- the queue of closed groups.
fn assert_same_state(want: &mut Bank, got: &mut Bank, what: &str) {
    for si in 0..want.specs().len() {
        // Compared as text, because a gated instance's coefficient is a
        // NaN and `NaN != NaN`: what must match here is the bytes' meaning,
        // and a NaN in the same slot is a match.
        assert_eq!(
            format!("{:?}", want.coef(si, None).unwrap()),
            format!("{:?}", got.coef(si, None).unwrap()),
            "{what}: spec {si}: coefficients"
        );
        let (wk, wc) = want.last_row(si, None).unwrap();
        let (gk, gc) = got.last_row(si, None).unwrap();
        assert_eq!(wk, gk, "{what}: spec {si}: last_row groups");
        assert!(
            wc.equals_missing(&gc),
            "{what}: spec {si}: last_row\n{wc:?}\n{gc:?}"
        );
        let (ws, gs) = (
            want.summary(si, None).unwrap(),
            got.summary(si, None).unwrap(),
        );
        assert!(
            ws.equals_missing(&gs),
            "{what}: spec {si}: summary\n{ws}\n{gs}"
        );
        let (wd, gd) = (
            want.describe(si, None).unwrap(),
            got.describe(si, None).unwrap(),
        );
        assert!(
            wd.equals_missing(&gd),
            "{what}: spec {si}: describe\n{wd}\n{gd}"
        );
    }
    let (wc, gc) = (
        want.closed_groups(None, false).unwrap(),
        got.closed_groups(None, false).unwrap(),
    );
    assert!(
        wc.equals_missing(&gc),
        "{what}: the closed-group queue\n{wc}\n{gc}"
    );
}

#[test]
fn the_fixture_is_what_it_says() {
    let h = header(&bytes());
    assert_eq!(h["format_version"], 2);
    assert_eq!(h["schema_version"], 5);
    let specs = specs_from_fixture();
    assert_eq!(specs.len(), NAMES.len());
    let names: Vec<&str> = specs.iter().map(|s| s.name.as_str()).collect();
    assert_eq!(names, NAMES);
    let json = serde_json::to_value(&specs).unwrap();
    // The generator specs as written, filled the way a bank fills them
    // (`Spec::fill_defaults`, E53) -- which is what the file holds.
    let mut want = generator_specs();
    want.iter_mut().for_each(Spec::fill_defaults);
    assert_eq!(json, serde_json::to_value(&want).unwrap());
    // The field schema 5 exists for, on the two specs that close groups.
    assert_eq!(json[0]["group_close"], "monotone");
    assert_eq!(json[1]["group_close"], "monotone");
    for i in 2..NAMES.len() {
        assert!(json[i]["group_close"].is_null(), "spec {i} closes nothing");
    }
    // Two groups closed and nobody read them, so the file carries their
    // rows and the high-water key that says so.
    let closed = h["closed"].as_array().expect("a closed-group queue");
    assert_eq!(closed.len(), 4, "two groups x two closing specs");
    assert_eq!(h["high_water"].as_array().unwrap().len(), 2);
    // And every stream still carries a last row and a summary.
    let states = h["states"].as_array().unwrap();
    assert_eq!(states.len(), NAMES.len());
    for per_spec in states {
        for per_group in per_spec.as_array().unwrap() {
            let st = &per_group.as_array().unwrap()[1];
            assert!(st["last_row"].is_object(), "no last row: {st}");
            assert!(st["summary"].is_object(), "no summary: {st}");
        }
    }
}

#[test]
fn a_schema_5_state_file_loads_with_everything_it_carries() {
    let bank = Bank::load_bytes(&bytes(), None);
    assert!(
        bank.is_ok(),
        "schema-5 state failed to load: {:?}",
        bank.err()
    );
    let specs = specs_from_fixture();
    assert!(Bank::load_bytes(&bytes(), Some(&specs)).is_ok());
    let mut restored = bank.unwrap();
    assert_same_state(&mut fresh(), &mut restored, "as loaded");
    // The lagged co-moments and the ring they come from survived: the last
    // group has three rows, fewer than `lags` reaches back, so the ring is
    // partly filled and the longest lag has nothing in it yet.
    let g = &restored.gram(0, Some("g2")).unwrap()[0];
    assert_eq!(g.lags.as_deref(), Some(&[1usize, 12][..]));
    let fresh_gram = fresh().gram(0, Some("g2")).unwrap()[0].clone();
    assert_eq!(g.lag_comoments, fresh_gram.lag_comoments);
    let lagged = g.lag_comoments.as_ref().expect("lagged co-moments");
    let k = 3 * 3;
    assert_eq!(lagged.len(), 2 * k, "one k x k block per lag");
    assert!(
        lagged[k..].iter().all(|v| *v == 0.0),
        "a lag of 12 has seen nothing in a group of ten rows"
    );
    assert!(lagged[..k].iter().any(|v| *v != 0.0), "a lag of 1 has");
}

#[test]
fn a_schema_5_state_continues_the_stream_to_the_bit() {
    let specs = specs_from_fixture();
    let mut want = fresh();
    let mut restored = Bank::load_bytes(&bytes(), Some(&specs)).unwrap();
    let next = frame(60, 25);
    let a = unnested(next.height(), want.fit_predict(&next).unwrap());
    let b = unnested(next.height(), restored.fit_predict(&next).unwrap());
    assert_same(&a, &b, "the restored state did not continue identically");
    assert_same_state(&mut want, &mut restored, "after continuing");
}

#[test]
fn a_schema_5_state_re_saves_byte_identically() {
    let restored = Bank::load_bytes(&bytes(), None).unwrap();
    let again = restored.save_bytes().unwrap();
    let h = header(&again);
    assert_eq!(h["format_version"], 2, "the envelope did not move");
    assert_eq!(h["schema_version"], online_core::SCHEMA_VERSION);
    let fixture = header(&bytes());
    if h["schema_version"] == fixture["schema_version"]
        && h["package_version"] == fixture["package_version"]
    {
        // Same writer: loading and saving is the identity, byte for byte.
        assert_eq!(again, bytes(), "the same writer re-saved different bytes");
    } else {
        // A later writer: the file must have moved to the current layout
        // and version, and nothing else.
        assert_ne!(again, bytes(), "saving should write the current schema");
    }
    let mut reloaded = Bank::load_bytes(&again, None).unwrap();
    let mut restored = restored;
    assert_same_state(&mut restored, &mut reloaded, "after re-save");
    assert_same_state(&mut fresh(), &mut reloaded, "after re-save, against fresh");
}

