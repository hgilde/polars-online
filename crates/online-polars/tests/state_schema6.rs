//! A schema-6 bank file: the layout tasks 45-55 introduced, plus task 63's
//! two `ew_cov` window keys and the names the 2026-09-07 naming pass
//! settled on. Every
//! spec carries `group_close`, the bank carries the rows of groups that have
//! closed and not yet been read (with the high-water group key that decides
//! when the next one closes), an `ew_cov` carries lagged co-moments and the
//! ring of rows they are computed from, and five models that did not exist
//! in schema 4 carry their state.
//!
//! `state_v1.rs`, `state_schema2.rs`, `state_schema3.rs` and
//! `state_schema4.rs` prove that files written before those tasks still load
//! and continue; this file is the other half of the promise, for the *next*
//! layout change.
//!
//! The fixture is frozen bytes for the same reasons as the others -- there
//! will be no schema-6 writer once the layout moves, and hard rule 1 keeps
//! binary files out of the repo -- and was generated from this build, by the
//! stream `frame` reproduces and the specs the file itself carries.
//!
//! **This file was `state_schema5.rs` until 2026-09-07.** Two things ended
//! that: `SCHEMA_VERSION` rose to 6, so this build cannot write a schema-5
//! file to freeze; and the naming pass renamed spec keys with no aliases, so
//! a *genuine* 0.2.0 file -- which names `horizon`, `n_max`, `sm_every` and
//! the rest -- no longer loads into a meaningful spec. That is the accepted
//! cost of renaming before 1.0, recorded here because this file is where a
//! reader would otherwise expect the old promise to hold. What it still
//! proves is the promise for the *next* layout change: these bytes load,
//! continue the stream to the bit, and re-save unchanged.
//!
//! Re-frozen a third time on 2026-09-07: the naming pass renamed five more
//! keys and one output column -- `rcov.n_max` to `block_rows` and `h_max` to
//! `max_bandwidth`, `kmeans.sm_every` to `split_merge_every`, the ridge
//! family's `coef0` to `coef_prior`, and `refresh_time`'s `n_ticks_<s>` to
//! `n_obs_<s>` -- for the same reason as the second: a bank carries its
//! specs verbatim.
//!
//! Re-frozen a second time on 2026-09-07: task 63a renamed three spec keys
//! (`corrchange.horizon`/`window` to one `span_rows`, `rcov.window` to
//! `preavg_rows`, `bocpd.truncate` to `prune_below`), and a bank file
//! carries its specs verbatim, so the old bytes name fields no builder has.
//! No compatibility was kept and none is owed: the renames landed before any
//! release carried them. The *format* is untouched, so this still exercises
//! the schema-6 loader.
//!
//! Re-frozen once before, on 2026-09-06, and the layout did **not** move: `hmm`'s
//! `min_periods` used to withhold a row from the update as well as from the
//! report, so the `hm` spec's state here was written by a model that has
//! since been corrected (docs/REVIEW-E54-E64.md H1). The three tests below
//! compare the file against a bank built afresh, so a deliberate change to
//! what a model computes has to be re-frozen here exactly as it is in
//! `crates/online-core/tests/golden.rs` -- and, like that one, only after
//! confirming the change was intended. Nothing about the *format* changed,
//! so the file exercises the same loader it always did.
//!
//! When `SCHEMA_VERSION` moves, keep this file and its fixture as they are:
//! the tests already ask only for what a converter must preserve, and
//! `a_schema_6_state_re_saves_byte_identically` is written to hold while the
//! writer is unchanged and to become the upgrade test when it is not.

