"""The experiments behind ``docs/REGIMES.md``: the regime detectors, measured
on streams whose truth is written down.

Everything here runs on ``po.sim.regimes`` (E64) or on a Monte-Carlo draw
whose null is published, and every number in the document comes from this
file. It is committed and **not** regenerated by the gate: the size study
alone is 2000 replications, which does not belong in a test that has to stay
under a second.

    uv run python scripts/regime_experiments.py all
    uv run python scripts/regime_experiments.py size

Experiments: ``recovery`` (task 53 -- does `hmm` recover the transition
matrix and the state means?), ``size`` (task 54 -- is `corrchange`'s monitor
the size its paper says, at 2000 replications?), ``power`` (task 54 --
size-adjusted power on a `0.5 -> 0.7` break), ``dhat`` (task 54 -- the
denominator both of those depend on, against the value it estimates),
``delay`` (tasks 54 and 55 -- false alarms and detection delay, for
`corrchange(window)` and `bocpd`, on the same simulated streams), ``epps``
(task 52 and E57 -- the Epps curve of an asynchronous stream, and what
refresh time and the lag inversion recover from it). ``all`` runs them in
that order.
"""

from __future__ import annotations

import sys
import time
import zlib

import numpy as np
import polars as pl

import polars_online as po
from polars_online import corr, prep, sim


def _seed(*parts: object) -> int:
    """A reproducible seed from a key. `hash()` is randomised per process for
    strings, so it cannot be used: an experiment in a committed document has
    to give the same numbers to whoever runs it."""
    return zlib.crc32(repr(parts).encode()) & 0xFFFF_FFFF


def _rule(title: str) -> None:
    print(f"\n## {title}\n")


def _table(head: list[str], rows: list[list[str]]) -> None:
    widths = [max(len(str(r[i])) for r in [head, *rows]) for i in range(len(head))]
    line = "| " + " | ".join(h.ljust(w) for h, w in zip(head, widths, strict=True)) + " |"
    print(line)
    print("|" + "|".join("-" * (w + 2) for w in widths) + "|")
    for r in rows:
        print("| " + " | ".join(str(c).ljust(w) for c, w in zip(r, widths, strict=True)) + " |")


# --- task 53: does the filter recover what generated the stream? -------------


def recovery(seeds: int = 8) -> None:
    """`hmm` on a two-state stream from `po.sim.regimes`, whose states differ
    in their **correlation** and in nothing else. Four ways to start it, and
    the answer is not the one the defaults give.

    The row's mean is zero in both states, so a state is visible only through
    the joint density -- which is the hard direction, and the one a
    correlation regime actually is.
    """
    _rule("Recovery: `hmm` against the stream that made it")
    setups = [
        ("seeded from the rows (`warm_rows`), learn", "seed", True, 0.01),
        ("true covariances, filter only", "true", False, 0.01),
        ("true covariances, and go on learning", "true", True, 0.01),
        ("true covariances, `precision_prior` = 1.0", "true", False, 1.0),
    ]
    scores: dict[str, list[float]] = {name: [] for name, *_ in setups}
    drift: list[float] = []
    for seed in range(seeds):
        out = sim.regimes(
            2,
            states=[0.1, 0.8],
            transition=[[0.99, 0.01], [0.02, 0.98]],
            n_blocks=10,
            bars_per_block=400,
            seed=seed,
        )
        rets = out["bars"].select(pl.col("x_1", "x_2").diff()).drop_nulls()
        df = rets.rename({"x_1": "x0", "x_2": "x1"})
        want = np.asarray(out["truth_rows"]["state"].to_list()[1:], dtype=float)
        sd = df.to_numpy().std(0)
        v = sd**2
        covs = [
            v[0],
            0.1 * sd[0] * sd[1],
            0.1 * sd[0] * sd[1],
            v[1],
            v[0],
            0.8 * sd[0] * sd[1],
            0.8 * sd[0] * sd[1],
            v[1],
        ]
        for name, start, learn, prior in setups:
            common = dict(
                features=["x0", "x1"],
                k=2,
                precision_prior=prior,
                learn=learn,
                halflife=4000.0,
            )
            if start == "true":
                spec = po.spec.hmm(
                    "h",
                    transition=[0.99, 0.01, 0.02, 0.98],
                    means=[0.0, 0.0, 0.0, 0.0],
                    covs=covs,
                    **common,
                )
            else:
                spec = po.spec.hmm("h", transition_prior=200.0, warm_rows=500, seed=seed, **common)
            bank = po.ModelBank([spec])
            got = bank.fit_predict(df)["h"].struct.unnest()
            hot = np.asarray(got["p_1"].fill_null(0.5).to_list()) > 0.5
            scores[name].append(
                float(max((hot == (want == 1)).mean(), (hot == (want == 0)).mean()))
            )
            if start == "seed" and learn:
                learned = bank.coef("h")["coef"].to_numpy()
                drift.append(float(np.abs(learned).max()))
    _table(
        ["how it was started", "mean state accuracy", "worst"],
        [
            [name, f"{np.mean(scores[name]):.3f}", f"{np.min(scores[name]):.3f}"]
            for name, *_ in setups
        ],
    )
    print(f"\n{seeds} seeds, 4000 rows each, two states at correlation 0.1 and 0.8")
    print(
        "\nThe seeded row is the finding: the default seeding is k-means on the\n"
        "rows, and rows from two zero-mean states differ only in their\n"
        f"covariance, so it splits them by *direction* instead -- the learned\n"
        f"state means reach {np.mean(drift):.2f} in absolute value where the truth\n"
        "is zero. A covariance regime needs the covariances to start from (or a\n"
        "feature in which the regime is a location shift).\n"
        "\nAnd the last row is `bocpd`'s `prior_scale` lesson again: a ridge of\n"
        "1.0 added to a covariance whose entries are about 1.0 halves every\n"
        "correlation, which is the whole of the signal here."
    )


# --- task 54: is the monitor the size its paper says? ------------------------


def _draw(t: int, rho: np.ndarray | float, rng: np.random.Generator, dist: str) -> np.ndarray:
    """A bivariate sample with correlation `rho` (per row, if it is a
    vector). WKD's tables are for **`t_5` innovations**, which is why the
    experiments report that and the Gaussian case side by side: the test is
    distribution-free in the limit, and how far from the limit `T = 500` is
    depends on the tail."""
    z = rng.standard_normal((t, 2))
    x = np.column_stack([z[:, 0], rho * z[:, 0] + np.sqrt(1 - np.asarray(rho) ** 2) * z[:, 1]])
    nu = 5
    if dist == "t5":
        # A multivariate t: one chi-square scale per row, shared by both
        # coordinates, which leaves the correlation at `rho` and makes the
        # extremes arrive in both at once.
        return x / np.sqrt(rng.chisquare(nu, size=(t, 1)) / nu)
    if dist == "t5_indep":
        # The other reading of "bivariate t_5": each coordinate its own
        # scale. Same marginals, no tail dependence, and -- measured -- a
        # different size.
        return x / np.sqrt(rng.chisquare(nu, size=(t, 2)) / nu)
    return x


def _monitor_flags(x: np.ndarray, horizon: int, alpha: float) -> list[bool]:
    df = pl.DataFrame({"x0": x[:, 0], "x1": x[:, 1]})
    spec = po.spec.corrchange(
        "c", features=["x0", "x1"], horizon=horizon, alpha=alpha, alpha_adjust="none"
    )
    out = po.ModelBank([spec]).fit_predict(df)["c"].struct.unnest()
    return [f for f in out["flag"].to_list() if f is not None]


def size(reps: int = 2000, alpha: float = 0.05) -> None:
    """Wied, Krämer & Dehling (2012) Table 1: the rejection rate of the
    constancy test under the null, which is its size.

    Their table is for **`t_5` innovations**, so that is the column the
    comparison is against; the Gaussian column is beside it because the test
    is distribution-free only in the limit and this is how far from it
    `T = 500` is.
    """
    _rule("Size: the monitor against WKD Table 1")
    published = {
        (-0.5, 500): 0.040,
        (0.0, 500): 0.035,
        (0.5, 500): 0.041,
        (-0.5, 1000): 0.038,
        (0.0, 1000): 0.034,
        (0.5, 1000): 0.039,
    }
    se = np.sqrt(alpha * (1 - alpha) / reps)
    rows = []
    for t in (500, 1000):
        for rho in (-0.5, 0.0, 0.5):
            cells = {}
            for dist in ("t5", "t5_indep", "normal"):
                hits = 0
                for r in range(reps):
                    rng = np.random.default_rng(_seed(t, round(rho, 3), r, dist))
                    hits += sum(_monitor_flags(_draw(t, rho, rng, dist), t, alpha))
                cells[dist] = hits / reps
            rows.append(
                [
                    t,
                    rho,
                    f"{published[(rho, t)]:.3f}",
                    f"{cells['t5']:.3f}",
                    f"{cells['t5_indep']:.3f}",
                    f"{cells['normal']:.3f}",
                ]
            )
    _table(
        ["T", "rho", "WKD Table 1", "t5 shared scale", "t5 independent", "Gaussian"],
        rows,
    )
    se = np.sqrt(alpha * (1 - alpha) / reps)
    print(f"\n{reps} replications each; nominal {alpha}, s.e. {se:.4f}")
    print(
        "\nAt `rho = 0` every distribution agrees with the paper. At"
        '\n`|rho| = 0.5` the two readings of "i.i.d. bivariate t_5" straddle'
        "\nit -- tail dependence makes the test liberal, independent tails make"
        "\nit conservative -- and Gaussian pairs land near the nominal 5 %. The"
        "\npaper's phrase does not say which, so the table cannot be matched to"
        "\na decimal; what this implementation can be held to is the level it"
        "\nasks for, which is what `tests/test_corrchange.py` pins."
    )


def _monitor_stat(x: np.ndarray, horizon: int) -> float:
    df = pl.DataFrame({"x0": x[:, 0], "x1": x[:, 1]})
    spec = po.spec.corrchange(
        "c", features=["x0", "x1"], horizon=horizon, alpha=0.05, alpha_adjust="none"
    )
    out = po.ModelBank([spec]).fit_predict(df)["c"].struct.unnest()
    return float(out["stat"].drop_nulls().to_list()[0])


def power(reps: int = 1000, alpha: float = 0.05) -> None:
    """WKD Table 2: power against a `0.5 -> 0.7` break at the midpoint.

    Reported twice: against the asymptotic critical value, which is what the
    model uses, and against the empirical null quantile from `reps` draws of
    the same length, which removes any finite-sample tilt in the size.
    """
    _rule("Power: a 0.5 -> 0.7 break at T/2")
    published = {500: 0.587, 1000: 0.830}
    rows = []
    for t in (500, 1000):
        for dist in ("t5", "t5_indep", "normal"):

            def stat(kind: str, rho: np.ndarray | float, r: int, t: int = t, dist: str = dist):
                rng = np.random.default_rng(_seed(kind, t, r, dist))
                return _monitor_stat(_draw(t, rho, rng, dist), t)

            null = np.array([stat("null", 0.5, r) for r in range(reps)])
            q = float(np.quantile(null, 1 - alpha))
            rho = np.where(np.arange(t) < t // 2, 0.5, 0.7)
            broken = np.array([stat("broken", rho, r) for r in range(reps)])
            rows.append(
                [
                    t,
                    dist,
                    f"{(broken > 1.3581).mean():.3f}",
                    f"{(broken > q).mean():.3f}",
                    f"{q:.3f}",
                    f"{published[t]:.3f}" if dist == "t5" else "",
                ]
            )
    _table(["T", "innovations", "power", "size-adjusted", "empirical 95%", "WKD Table 2"], rows)
    print(
        f"\n{reps} replications each, nominal {alpha}, asymptotic critical value 1.3581."
        "\nThe power depends on the DGP the same way the size does, and by more:"
        "\non Gaussian pairs this implementation is well above WKD's table, on a"
        "\ntail-dependent t_5 it is below it, and the readings bracket their"
        "\nfigure. The size-adjusted column is the one to read across"
        "\ndistributions, since it takes the null quantile from the same draw."
    )


def _numerator(x: np.ndarray) -> float:
    """`max_j (j/sqrt(T)) |rho_j - rho_T|`, the monitor's statistic before it
    is divided by `D-hat`. Written here in one pass so `D-hat` itself can be
    recovered from the reported statistic."""
    t = len(x)
    cs, cs2 = np.cumsum(x, 0), np.cumsum(x * x, 0)
    cxy = np.cumsum(x[:, 0] * x[:, 1])
    j = np.arange(1, t + 1)
    mx, my = cs[:, 0] / j, cs[:, 1] / j
    vx, vy = cs2[:, 0] / j - mx**2, cs2[:, 1] / j - my**2
    with np.errstate(invalid="ignore", divide="ignore"):
        r = (cxy / j - mx * my) / np.sqrt(vx * vy)
    return float(np.nanmax(((j / np.sqrt(t)) * np.abs(r - r[-1]))[1:]))


def dhat(reps: int = 200) -> None:
    """Where the size and the power go under heavy tails: `D-hat`, the
    delta-method long-run standard deviation of `sqrt(T)*rho-hat` that the
    monitor divides by.

    For an elliptical distribution with kurtosis parameter `kappa` the
    asymptotic value is `(1 - rho^2) sqrt(1 + kappa)`: `0.75` at `rho = 0.5`
    for a Gaussian, and `1.299` for a `t_5`, whose `kappa` is `2/(nu - 4) =
    2`. `D-hat` is recovered here as (the longhand numerator) / (the reported
    statistic), so it is the estimator the model actually used.
    """
    _rule("D-hat: the denominator, against what it is estimating")
    rho = 0.5
    rows = []
    for dist, kappa in (("normal", 0.0), ("t5", 2.0), ("t5_indep", None)):
        for t in (500, 2000):
            got = []
            for r in range(reps):
                x = _draw(t, rho, np.random.default_rng(_seed("D", t, r, dist)), dist)
                got.append(_numerator(x) / _monitor_stat(x, t))
            want = (1 - rho**2) * np.sqrt(1 + kappa) if kappa is not None else None
            rows.append(
                [
                    dist,
                    t,
                    f"{np.mean(got):.3f}",
                    f"{np.median(got):.3f}",
                    f"{np.std(got):.3f}",
                    f"{want:.3f}" if want is not None else "-",
                ]
            )
    _table(["innovations", "T", "mean", "median", "sd", "asymptotic"], rows)
    print(
        f"\n{reps} replications each, at rho = 0.5.\n"
        "\nUnder Gaussian pairs the estimator is exactly right and tight: 0.750"
        "\nagainst 0.750 at T = 2000, with a standard deviation of 0.03. Under a"
        "\ntail-dependent t_5 it is **biased low by about 15 %, and no better at"
        "\nT = 2000 than at T = 500**, with a standard deviation that is 40 % of"
        "\nits own level and a median well below its mean. That is the signature"
        "\nof an estimator whose inputs are fourth moments of a distribution"
        "\nwhose fourth moment has infinite variance -- a t_5 has kurtosis only"
        "\njust, at nu > 4 -- so there is no rate at which it settles."
        "\n\nA denominator 15 % too small inflates Q by about 18 %, which is the"
        "\nliberal size in section 2; the scatter is what costs the"
        "\nsize-adjusted power in section 3. Both symptoms are this one number."
    )


# --- tasks 54 and 55: how long to a false alarm, how long to the alarm -------


def _stream(seed: int, *, broken: bool) -> pl.DataFrame:
    states = [0.2, 0.7] if broken else [0.2, 0.2]
    out = sim.regimes(
        3,
        states=states,
        # The off-diagonal with `durations = [1, 1]` is the deterministic
        # alternation: block 0 in state 0, block 1 in state 1.
        transition=[[0.0, 1.0], [1.0, 0.0]],
        n_blocks=2,
        bars_per_block=1000,
        durations=[1, 1],
        seed=seed,
    )
    rets = out["bars"].select(pl.col("x_1", "x_2", "x_3").diff()).drop_nulls()
    return rets.rename({"x_1": "x0", "x_2": "x1", "x_3": "x2"})


def delay(seeds: int = 20) -> None:
    """Two detectors on the same streams, one with a break in the
    correlation at row 1000 and one without. What each costs in false alarms
    and what each takes to find the break.

    The alarm rules are the ones each model actually offers.
    `corrchange(window)` raises a flag. `bocpd` does not: a correlation
    change never moves `p_change` (the row is not surprising, the *sequence*
    of rows is), so its alarm is the run-length posterior moving -- the row
    it says the current run began on jumping forward by more than 50.
    """
    _rule("Alarms: false alarms on a quiet stream, and delay on a broken one")
    win = po.spec.corrchange(
        "w",
        features=["x0", "x1", "x2"],
        kind="window",
        window=100,
        n_perm=100,
        permute_every=100,
        alpha=0.05,
        seed=0,
    )
    boc = po.spec.bocpd(
        "b",
        features=["x0", "x1", "x2"],
        hazard=500.0,
        emission="gaussian",
        prior_nu=5.0,
        prior_scale=[0.1],
        truncate=1e-8,
        max_run=1200,
    )

    def window_alarms(df: pl.DataFrame) -> list[int]:
        out = po.ModelBank([win]).fit_predict(df)["w"].struct.unnest()
        return [i for i, f in enumerate(out["flag"].to_list()) if f]

    def bocpd_alarms(df: pl.DataFrame) -> list[int]:
        out = po.ModelBank([boc]).fit_predict(df)["b"].struct.unnest()
        mode = out["run_mode"].to_list()
        began = [None if m is None else i - m for i, m in enumerate(mode)]
        return [
            i
            for i in range(2, len(began))
            if began[i] is not None and began[i - 1] is not None and began[i] - began[i - 1] > 50
        ]

    rows = []
    for name, alarms in (("corrchange(window)", window_alarms), ("bocpd", bocpd_alarms)):
        false_alarms, delays, dated, missed = 0, [], [], 0
        for seed in range(seeds):
            false_alarms += len(alarms(_stream(seed, broken=False)))
            after = [a for a in alarms(_stream(seed, broken=True)) if a >= 1000]
            if after:
                delays.append(after[0] - 1000)
                dated.append(after[0])
            else:
                missed += 1
        rows.append(
            [
                name,
                f"{false_alarms / (seeds * 2000) * 1000:.2f}",
                f"{seeds - missed}/{seeds}",
                f"{np.median(delays):.0f}" if delays else "-",
                f"{np.max(delays):.0f}" if delays else "-",
            ]
        )
    _table(
        [
            "detector",
            "false alarms / 1000 quiet rows",
            "found the break",
            "median delay",
            "worst delay",
        ],
        rows,
    )
    print(
        f"\n{seeds} seeds; three series, 2000 rows, the break at row 1000, correlation"
        "\n0.2 -> 0.7. Two windows that slide by one row are almost the same"
        "\nwindows, so the window detector's flags come in runs and its rate is"
        "\nnearer a fraction of rows above the quantile than a count of events."
        "\n\nThe window detector is looking at exactly this and flags it"
        "\nfast; `bocpd` is not built for it -- it is a full joint model, and this is"
        "\nthe one break its `p_change` cannot see -- but its run length finds it and"
        "\ndates it, and it does so with a much quieter stream of false alarms."
    )


# --- task 52 and E57: the Epps curve -----------------------------------------


def epps() -> None:
    """The Epps effect on a simulated asynchronous stream, and the two
    things this library offers against it: refresh-time sampling, and
    inverting the attenuation from the lagged co-moments."""
    _rule("Epps: what asynchrony costs, and what gets it back")
    truth = 0.8
    out = sim.regimes(
        2,
        states=[truth],
        transition=[[1.0]],
        n_blocks=1,
        bars_per_block=120_000,
        async_rates=[0.25, 0.25],
        seed=7,
    )
    bars = out["bars"]
    filled = bars.select(pl.col("x_1", "x_2").forward_fill()).drop_nulls().to_numpy()
    rows = []
    for step in (1, 2, 5, 20, 100, 500):
        r = np.diff(filled[::step], axis=0)
        rows.append([step, len(r), f"{np.corrcoef(r.T)[0, 1]:.3f}"])
    _table(["sampling interval", "returns", "correlation"], rows)
    print(f"\nthe truth is {truth}")

    long = (
        bars.select("t", "x_1", "x_2")
        .unpivot(index="t", variable_name="series", value_name="px")
        .drop_nulls()
        .sort("t")
    )
    grid = prep.refresh_time(
        long, series="series", names=["x_1", "x_2"], time="t", value="px"
    ).collect()
    g = grid.select(pl.col("x_1_value", "x_2_value").diff()).drop_nulls().to_numpy()
    kept = float(grid["retained_fraction"].mean())
    print(
        f"\nrefresh time: {len(g)} points ({kept:.0%} of the ticks on the grid kept),"
        f" correlation {np.corrcoef(g.T)[0, 1]:.3f}"
    )

    r1 = np.diff(filled, axis=0)
    df = pl.DataFrame({"x0": r1[:, 0], "x1": r1[:, 1]})
    top = 96
    spec = po.spec.ew_cov("c", features=["x0", "x1"], lam=1.0, stats=[], lags=list(range(1, top)))
    bank = po.ModelBank([spec])
    bank.fit_predict(df)
    g = bank.gram("c")[0]
    _table(
        ["L", "inverted correlation"],
        [[L, f"{corr.epps_invert(g, L=L)[0, 1]:.3f}"] for L in (1, 2, 4, 8, 16, 32, 64, top)],
    )
    print(
        "\nThe lag inversion reads every one of the fine returns and needs no grid,"
        "\nand `L` is the same trade the sampling interval is: too small and the"
        "\ncross-covariance is still out at longer lags, too large and the sum is"
        "\nnoise. It is a state a bank already keeps (`ew_cov(lags=...)`), which is"
        "\nthe reason it is here."
    )


EXPERIMENTS = {
    "recovery": recovery,
    "size": size,
    "power": power,
    "dhat": dhat,
    "delay": delay,
    "epps": epps,
}


def main(argv: list[str]) -> int:
    which = argv[1:] or ["all"]
    if which == ["all"]:
        which = list(EXPERIMENTS)
    for name in which:
        if name not in EXPERIMENTS:
            print(f"unknown experiment {name!r}; one of {', '.join(EXPERIMENTS)}")
            return 2
        t0 = time.perf_counter()
        EXPERIMENTS[name]()
        print(f"\n_{name}: {time.perf_counter() - t0:.1f}s_")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
